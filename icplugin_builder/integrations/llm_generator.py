"""The LLM_Generator: scoped Kiro CLI dispatch with cost gating (task 14.1).

The ``LLM_Generator`` is the *reasoning* half of the generation split (design
"Generation_Engine -> LLM_Generator"). Everything mechanical is produced by the
``insight-plugin`` CLI and template rendering with zero LLM calls; this wrapper
is invoked **only** for the three reasoning artifact kinds -- action logic,
field descriptions, and help text (Req 3.2) -- and only when no matching
template is available (Req 3.4). Each artifact is generated by prompting the
Kiro CLI as a subprocess through :func:`asyncio.create_subprocess_exec`, feeding
it only the relevant scoped slice of the spec (design "Prompt scoping").

Every dispatch is gated by the :class:`~icplugin_builder.core.cost_controller.CostController`:

* :meth:`LLMGenerator.generate` first calls :meth:`CostController.authorize`;
  when the session token budget is reached or the per-user request rate is
  exceeded, the invocation is **not** dispatched and a :class:`CostLimitError`
  carrying the controller's :class:`Decision` is raised (Req 4.2, 4.5).
* On a successful invocation the tokens consumed are recorded on the session's
  cumulative total via :meth:`CostController.record_usage` (Req 3.5).
* If the invocation fails -- the Kiro CLI cannot be launched or exits non-zero
  -- the step is halted and the invocation is excluded from the cumulative total
  by recording it as a failure (Req 3.7).

**Token measurement precedence** (design "Token accounting with the Kiro CLI"):
1. If the Kiro CLI emits a machine-readable usage figure (structured JSON on
   stdout or a ``total_tokens: N`` usage line), that reported value is used.
2. Otherwise tokens are **estimated** from the prompt plus completion text with a
   ~4-characters-per-token heuristic and flagged as an estimate so the UI can
   mark the session total accordingly.
The recorded figure is always a non-negative integer (Req 3.6).
"""

from __future__ import annotations

import asyncio
import json
import math
import re
from dataclasses import dataclass
from typing import Any, Mapping, Optional, Sequence, Union

from icplugin_builder.core.cost_controller import CostController, Decision
from icplugin_builder.core.generation import REASONING_ARTIFACT_KINDS, ArtifactKind

__all__ = [
    "DEFAULT_EXECUTABLE",
    "CHARS_PER_TOKEN",
    "TOKEN_SOURCE_REPORTED",
    "TOKEN_SOURCE_ESTIMATED",
    "LLMGeneratorError",
    "CostLimitError",
    "TokenMeasurement",
    "GenerationResult",
    "LLMGenerator",
    "estimate_tokens",
    "parse_reported_tokens",
]

#: The default Kiro CLI executable name (resolved on ``PATH``).
DEFAULT_EXECUTABLE = "kiro"

#: The character-per-token divisor for the estimation fallback (~4 chars/token).
CHARS_PER_TOKEN = 4

#: Token-measurement source markers recorded alongside the figure.
TOKEN_SOURCE_REPORTED = "reported"
TOKEN_SOURCE_ESTIMATED = "estimated"

#: JSON/usage-line keys that carry a machine-readable token figure, in priority order.
_USAGE_KEYS = ("total_tokens", "token_count", "tokens")

#: Matches a ``key: N`` / ``key=N`` usage line emitted by the CLI.
_USAGE_LINE = re.compile(
    r"\b(?:total_tokens|token_count|tokens)\b\s*[:=]\s*(\d+)",
    re.IGNORECASE,
)


class LLMGeneratorError(Exception):
    """Raised when a Kiro CLI invocation cannot be dispatched or fails.

    Carries the argument vector, exit code, and captured output so the caller can
    surface the failing step and its error message (Req 3.7, 19.1).
    """

    def __init__(
        self,
        message: str,
        *,
        command: Optional[Sequence[str]] = None,
        returncode: Optional[int] = None,
        stdout: str = "",
        stderr: str = "",
    ) -> None:
        super().__init__(message)
        self.command = tuple(command) if command is not None else ()
        self.returncode = returncode
        self.stdout = stdout
        self.stderr = stderr


class CostLimitError(LLMGeneratorError):
    """Raised when the Cost_Controller blocks an invocation before dispatch.

    The invocation never reached the Kiro CLI: the session token budget was
    reached (Req 4.2) or the per-user request rate was exceeded (Req 4.5). The
    controller's :class:`Decision` -- including its user-facing ``message`` and,
    for a rate-limit rejection, ``retry_after_seconds`` -- is attached so the
    caller can surface it verbatim.
    """

    def __init__(self, decision: Decision) -> None:
        super().__init__(decision.message or "LLM invocation blocked by cost controls")
        self.decision = decision


@dataclass(frozen=True)
class TokenMeasurement:
    """How many tokens an invocation consumed and how that figure was obtained.

    Attributes:
        tokens: the non-negative token count (Req 3.6).
        source: :data:`TOKEN_SOURCE_REPORTED` when taken from the Kiro CLI's own
            machine-readable usage figure, or :data:`TOKEN_SOURCE_ESTIMATED` when
            derived from the ~4-chars/token heuristic fallback.
    """

    tokens: int
    source: str

    @property
    def estimated(self) -> bool:
        """Return ``True`` iff the figure is an estimate rather than reported."""
        return self.source == TOKEN_SOURCE_ESTIMATED


@dataclass(frozen=True)
class GenerationResult:
    """The outcome of a successful :meth:`LLMGenerator.generate` call.

    Attributes:
        kind: the reasoning :class:`ArtifactKind` that was generated.
        content: the artifact text returned by the Kiro CLI.
        measurement: the token figure and its source for this invocation.
        session_total: the cumulative session token total after recording this
            invocation (Req 3.5, 3.6).
    """

    kind: ArtifactKind
    content: str
    measurement: TokenMeasurement
    session_total: int

    @property
    def tokens(self) -> int:
        """The tokens consumed by this invocation."""
        return self.measurement.tokens

    @property
    def estimated(self) -> bool:
        """Return ``True`` iff the token figure is an estimate (Req token accounting)."""
        return self.measurement.estimated


# --- Kiro CLI output cleaning ------------------------------------------------

_ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")


def _clean_cli_output(stdout: str) -> str:
    """Strip ANSI codes, the Kiro CLI '> ' prefix, markdown fences, monologue, and the credits footer.

    Returns the LLM-generated content only, suitable for use as an artifact body.
    """
    text = _ANSI_RE.sub("", stdout)
    lines = text.strip().split("\n")
    # Remove trailing credits/timing line (e.g. " ▸ Credits: 0.05 • Time: 2s")
    while lines and (lines[-1].strip().startswith("\u25b8") or lines[-1].strip() == ""):
        lines.pop()
    # Strip leading "> " prompt prefix from each line
    cleaned = []
    for line in lines:
        if line.startswith("> "):
            cleaned.append(line[2:])
        else:
            cleaned.append(line)
    # Remove markdown fence artifacts that leak from the LLM (```python, ```, bare "python")
    # Remove LLM inner-monologue lines that sometimes leak into output
    _MONOLOGUE_PREFIXES = ("Wait,", "Let me", "Actually,", "Hmm,", "OK,", "Ok,", "Sure,", "Here", "I'll", "I need")
    final = []
    for line in cleaned:
        stripped = line.strip()
        if stripped in ("```python", "```", "python", "```py"):
            continue
        # Skip monologue lines (only at the start before code begins)
        if not final and any(stripped.startswith(prefix) for prefix in _MONOLOGUE_PREFIXES):
            continue
        final.append(line)
    # Strip trailing monologue that sometimes appears after code
    while final and any(final[-1].strip().startswith(prefix) for prefix in _MONOLOGUE_PREFIXES):
        final.pop()

    result = "\n".join(final).strip()

    # Normalize indentation: if all lines are indented more than expected (e.g. 16 spaces
    # instead of 0 for standalone code), strip the common leading whitespace.
    result_lines = result.split("\n")
    if result_lines:
        # Find minimum non-empty indent
        indents = [len(line) - len(line.lstrip()) for line in result_lines if line.strip()]
        if indents:
            min_indent = min(indents)
            if min_indent > 0:
                result_lines = [line[min_indent:] if len(line) >= min_indent else line for line in result_lines]
                result = "\n".join(result_lines)

    return result


def estimate_tokens(text: str) -> int:
    """Estimate the token count of ``text`` with a ~4-characters-per-token heuristic.

    This is the fallback used when the Kiro CLI does not report an exact figure
    (design "Token accounting with the Kiro CLI", step 2). The result is a
    non-negative integer; empty text estimates to ``0``.
    """
    if not text:
        return 0
    return math.ceil(len(text) / CHARS_PER_TOKEN)


def parse_reported_tokens(stdout: str) -> Optional[int]:
    """Extract a machine-readable token figure from Kiro CLI ``stdout``.

    Recognizes, in order: the whole output parsed as a JSON object carrying a
    usage figure (``total_tokens`` / ``token_count`` / ``tokens``, possibly nested
    under a ``usage`` object), a single line that is such a JSON object, or a
    plain ``total_tokens: N`` / ``tokens=N`` usage line.

    Returns:
        The reported non-negative token count, or ``None`` when no reliable
        figure is present (in which case the caller estimates instead).
    """
    if not stdout:
        return None

    whole = _tokens_from_json(stdout.strip())
    if whole is not None:
        return whole

    for line in stdout.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        from_json = _tokens_from_json(stripped)
        if from_json is not None:
            return from_json
        match = _USAGE_LINE.search(stripped)
        if match is not None:
            return int(match.group(1))
    return None


def _tokens_from_json(text: str) -> Optional[int]:
    """Return a usage figure from ``text`` parsed as JSON, or ``None``."""
    try:
        data = json.loads(text)
    except (ValueError, TypeError):
        return None
    return _search_usage(data)


def _search_usage(data: Any) -> Optional[int]:
    """Search a decoded JSON value for a usage figure under a known key."""
    if not isinstance(data, Mapping):
        return None
    for key in _USAGE_KEYS:
        if key in data:
            value = _coerce_non_negative_int(data[key])
            if value is not None:
                return value
    for value in data.values():
        found = _search_usage(value)
        if found is not None:
            return found
    return None


def _coerce_non_negative_int(value: Any) -> Optional[int]:
    """Coerce ``value`` to a non-negative int, or ``None`` if it is not one."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value if value >= 0 else None
    if isinstance(value, str):
        try:
            parsed = int(value.strip())
        except ValueError:
            return None
        return parsed if parsed >= 0 else None
    return None


class LLMGenerator:
    """Async wrapper over the Kiro CLI that generates reasoning artifacts.

    The wrapper is deliberately thin: it validates that the requested kind is a
    reasoning kind, gates the call through the :class:`CostController`, builds a
    scoped prompt, runs the Kiro CLI via :func:`asyncio.create_subprocess_exec`,
    measures the tokens consumed, and records the usage on the session total. It
    is the *only* seam that invokes the LLM (Req 3.2).
    """

    def __init__(
        self,
        cost_controller: CostController,
        executable: Union[str, Sequence[str]] = DEFAULT_EXECUTABLE,
    ) -> None:
        """Configure the generator.

        Args:
            cost_controller: the shared :class:`CostController` every invocation
                is authorized and recorded against.
            executable: the Kiro CLI command -- either the binary name/path or a
                full argument-vector prefix (e.g. ``["kiro", "generate"]``).
        """
        self._cost_controller = cost_controller
        if isinstance(executable, str):
            self._command_prefix = [executable]
        else:
            self._command_prefix = [str(part) for part in executable]

    @property
    def cost_controller(self) -> CostController:
        """The :class:`CostController` this generator gates through."""
        return self._cost_controller

    async def generate(
        self,
        kind: Union[ArtifactKind, str],
        scoped_context: Mapping[str, Any],
        *,
        session_id: str,
        user_id: str,
    ) -> GenerationResult:
        """Generate a reasoning artifact through the Kiro CLI, gated by cost.

        Args:
            kind: the artifact kind; must be one of the reasoning kinds
                (``action_logic``, ``field_description``, ``help_text``) -- the
                only kinds the LLM is ever invoked for (Req 3.2). Deterministic
                kinds are rejected before any dispatch.
            scoped_context: the relevant slice of the spec to prompt with (the
                single action being authored plus the connection contract, etc.);
                the whole project tree is never sent (design "Prompt scoping").
            session_id: the session whose token budget and cumulative total
                govern and record this invocation.
            user_id: the user whose per-minute request rate governs this
                invocation.

        Returns:
            A :class:`GenerationResult` with the generated content, the token
            measurement, and the updated cumulative session total.

        Raises:
            ValueError: if ``kind`` is not a reasoning artifact kind.
            CostLimitError: if the Cost_Controller blocks the invocation (budget
                reached or rate limit exceeded); nothing is dispatched.
            LLMGeneratorError: if the Kiro CLI cannot be launched or exits
                non-zero; the invocation is excluded from the session total.
        """
        resolved_kind = self._resolve_reasoning_kind(kind)

        decision = self._cost_controller.authorize(session_id, user_id)
        if not decision.authorized:
            raise CostLimitError(decision)

        prompt = self._build_prompt(resolved_kind, scoped_context)
        command = [*self._command_prefix, "chat", "--no-interactive"]

        try:
            returncode, stdout, stderr = await self._invoke(command, prompt)
        except FileNotFoundError as error:
            # The invocation never produced output; exclude it from the total (Req 3.7).
            self._cost_controller.record_usage(session_id, estimate_tokens(prompt), succeeded=False)
            raise LLMGeneratorError(
                f"Kiro CLI executable not found: {self._command_prefix[0]!r}; "
                "install the Kiro CLI and ensure it is on PATH",
                command=command,
            ) from error

        if returncode != 0:
            # Failed invocation: halt the step, exclude from the total (Req 3.7).
            self._cost_controller.record_usage(session_id, estimate_tokens(prompt), succeeded=False)
            raise LLMGeneratorError(
                f"Kiro CLI generation for {resolved_kind.value!r} failed with exit code {returncode}",
                command=command,
                returncode=returncode,
                stdout=stdout,
                stderr=stderr,
            )

        content = _clean_cli_output(stdout)
        measurement = self._measure_tokens(prompt=prompt, stdout=stdout, content=content)
        session_total = self._cost_controller.record_usage(session_id, measurement.tokens, succeeded=True)
        return GenerationResult(
            kind=resolved_kind,
            content=content,
            measurement=measurement,
            session_total=session_total,
        )

    @staticmethod
    def _resolve_reasoning_kind(kind: Union[ArtifactKind, str]) -> ArtifactKind:
        """Coerce ``kind`` to an :class:`ArtifactKind` and require a reasoning kind.

        Raises:
            ValueError: if ``kind`` is unknown or not a reasoning kind. The LLM is
                never invoked for deterministic artifacts (Req 3.2).
        """
        try:
            resolved = ArtifactKind(kind)
        except ValueError as error:
            raise ValueError(f"unknown artifact kind: {kind!r}") from error
        if resolved not in REASONING_ARTIFACT_KINDS:
            raise ValueError(
                f"{resolved.value!r} is not a reasoning artifact kind; the LLM_Generator only serves "
                f"{', '.join(sorted(k.value for k in REASONING_ARTIFACT_KINDS))}"
            )
        return resolved

    @staticmethod
    def _build_prompt(kind: ArtifactKind, scoped_context: Mapping[str, Any]) -> str:
        """Build the scoped Kiro CLI prompt for ``kind`` from ``scoped_context``.

        This generator now serves **prose** artifacts only -- field descriptions
        and help text. The code kinds (``action_logic``, ``api_client``,
        ``connection_logic``) are delegated to the Kiro CLI running as an agent
        in the plugin's working tree (see
        :mod:`icplugin_builder.integrations.plugin_agent`), so the elaborate
        code-generation prompts that used to live here are gone.

        They were removed rather than moved. They restated the plugin conventions
        that the operator's Kiro skills already define, and the copy had drifted:
        it disagreed with the ``plugin-spec`` steering on credential field types
        and hardcoded one specific vendor's API base URL into the prompt used for
        *every* plugin. The agent reads the real skills instead.
        """
        try:
            context_json = json.dumps(dict(scoped_context), sort_keys=True, default=str)
        except (TypeError, ValueError):
            context_json = json.dumps({key: str(value) for key, value in dict(scoped_context).items()}, sort_keys=True)
        return f"kind={kind.value}\ncontext={context_json}\n"

    def _measure_tokens(self, *, prompt: str, stdout: str, content: str) -> TokenMeasurement:
        """Measure tokens by the reported figure, falling back to an estimate.

        Prefers a machine-readable usage figure from the Kiro CLI ``stdout``
        (step 1); otherwise estimates from the prompt plus the completion content
        (step 2), flagged as an estimate.
        """
        reported = parse_reported_tokens(stdout)
        if reported is not None:
            return TokenMeasurement(tokens=reported, source=TOKEN_SOURCE_REPORTED)
        estimated = estimate_tokens(prompt) + estimate_tokens(content)
        return TokenMeasurement(tokens=estimated, source=TOKEN_SOURCE_ESTIMATED)

    async def _invoke(self, command: Sequence[str], prompt: str) -> tuple:
        """Run the Kiro CLI ``command``, feeding ``prompt`` on stdin.

        Returns:
            A ``(returncode, stdout, stderr)`` tuple with the decoded output.

        Raises:
            FileNotFoundError: if the executable cannot be found.
        """
        process = await asyncio.create_subprocess_exec(
            *command,
            stdin=asyncio.subprocess.PIPE,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        stdout_bytes, stderr_bytes = await process.communicate(prompt.encode("utf-8"))
        stdout = stdout_bytes.decode("utf-8", errors="replace")
        stderr = stderr_bytes.decode("utf-8", errors="replace")
        returncode = process.returncode if process.returncode is not None else -1
        return returncode, stdout, stderr
